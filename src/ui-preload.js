// Bridge between the local UI renderer and the main process. Only these calls are exposed.
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('airlock', {
  platform: process.platform,
  setChatBounds: (rect) => ipcRenderer.send('chat:bounds', rect),
  setChatVisible: (visible) => ipcRenderer.send('chat:visible', visible),
  sendToChat: (text) => ipcRenderer.invoke('chat:send', text),
  onFill: (cb) => ipcRenderer.on('airlock:fill', (_e, copy) => cb(copy)),
  copyGesture: () => ipcRenderer.sendSync('copy:gesture'),
  openExternal: (url) => ipcRenderer.send('open-external', url),
  terminalMenu: (state) => ipcRenderer.send('terminal:menu', state),
  onTerminalMenu: (cb) => ipcRenderer.on('terminal:menu-action', (_e, action) => cb(action)),

  initial: ipcRenderer.sendSync('settings:initial'),
  setSettings: (patch) => ipcRenderer.send('settings:set', patch),
  onTheme: (cb) => ipcRenderer.on('theme:changed', (_e, theme) => cb(theme)),
  openDataFolder: () => ipcRenderer.send('data:open'),

  listShells: () => ipcRenderer.invoke('shells:list'),
  ptyStart: (opts) => ipcRenderer.send('pty:start', opts),
  ptyInput: (id, data) => ipcRenderer.send('pty:input', id, data),
  ptyResize: (id, size) => ipcRenderer.send('pty:resize', id, size),
  ptyActivate: (id) => ipcRenderer.send('pty:activate', id),
  ptyClose: (id) => ipcRenderer.send('pty:close', id),
  ptyConfirmClose: (id) => ipcRenderer.invoke('pty:confirm-close', id),
  onPtyData: (cb) => ipcRenderer.on('pty:data', (_e, id, data) => cb(id, data)),
  onPtyExit: (cb) => ipcRenderer.on('pty:exit', (_e, id, code) => cb(id, code)),
  reportCwd: (id, cwd) => ipcRenderer.send('pty:cwd', id, cwd),
  onDownloadDone: (cb) => ipcRenderer.on('download:done', (_e, info) => cb(info)),
  onUsage: (cb) => ipcRenderer.on('usage:update', (_e, usage) => cb(usage)),
  refreshUsage: () => ipcRenderer.send('usage:refresh'),
  listSnippets: () => ipcRenderer.invoke('snippets:list'),
  saveSnippets: (list) => ipcRenderer.invoke('snippets:save', list),
  chooseSnippetsFolder: () => ipcRenderer.invoke('snippets:choose-folder'),
  resetSnippetsFolder: () => ipcRenderer.invoke('snippets:reset-folder'),
  readmeSnippets: (id) => ipcRenderer.invoke('readme:snippets', id),
  teamList: (repo) => ipcRenderer.invoke('team:list', repo),
  teamSave: (snippet) => ipcRenderer.invoke('team:save', snippet),
  teamDelete: (snippet) => ipcRenderer.invoke('team:delete', snippet),
  listHistory: () => ipcRenderer.invoke('history:list'),
  addHistory: (command) => ipcRenderer.send('history:add', command),
  saveScratch: (file) => ipcRenderer.invoke('scratch:save', file),
  loadScratchState: () => ipcRenderer.invoke('scratch:load'),
  saveScratchState: (state) => ipcRenderer.send('scratch:state', state),
  readRunsheet: () => ipcRenderer.invoke('runsheet:read'),
  listRunsheets: () => ipcRenderer.invoke('runsheet:list'),
  chooseRunsheetFolder: () => ipcRenderer.invoke('runsheet:choose-folder'),
  openRunsheet: (relative) => ipcRenderer.invoke('runsheet:open', relative),
  saveRunsheet: (relative, text, expected) => ipcRenderer.invoke('runsheet:save', relative, text, expected),
  confirmDiscardRunsheet: () => ipcRenderer.invoke('runsheet:confirm-discard'),
  setWebBounds: (rect) => ipcRenderer.send('web:bounds', rect),
  setWebVisible: (visible) => ipcRenderer.send('web:visible', visible),
  webGo: (input) => ipcRenderer.send('web:go', input),
  webBack: () => ipcRenderer.send('web:back'),
  webForward: () => ipcRenderer.send('web:forward'),
  webReload: () => ipcRenderer.send('web:reload'),
  webExternal: () => ipcRenderer.send('web:external'),
  webSetAutoRun: (enabled) => ipcRenderer.invoke('web:set-auto-run', enabled),
  webRemoveAutoRun: (origin) => ipcRenderer.invoke('web:remove-auto-run', origin),
  onWebState: (cb) => ipcRenderer.on('web:state', (_e, state) => cb(state)),
  onWebError: (cb) => ipcRenderer.on('web:error', (_e, message) => cb(message)),
  onWebFocusAddress: (cb) => ipcRenderer.on('web:focus-address', () => cb()),
  loadScrollback: () => ipcRenderer.invoke('scrollback:load'),
  saveScrollback: (tabs) => ipcRenderer.send('scrollback:save', tabs),
  listRemotes: () => ipcRenderer.invoke('remotes:list'),
  saveRemote: (req) => ipcRenderer.invoke('remotes:save', req),
  deleteRemote: (req) => ipcRenderer.invoke('remotes:delete', req),
  testRemote: (req) => ipcRenderer.invoke('remotes:test', req),
  onePasswordItems: () => ipcRenderer.invoke('remotes:op-items'),
  ptyDisconnect: (id) => ipcRenderer.send('pty:disconnect', id),
  remoteTransfer: (req) => ipcRenderer.invoke('remote:transfer', req),
  confirmRemoteRun: (req) => ipcRenderer.invoke('remote:confirm-run', req),
  awsProfiles: (id) => ipcRenderer.invoke('aws:profiles', id),
  awsCommand: (id, name) => ipcRenderer.invoke('aws:command', id, name),
});
