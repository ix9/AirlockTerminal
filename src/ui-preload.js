// Bridge between the local UI renderer and the main process. Only these calls are exposed.
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('airlock', {
  platform: process.platform,
  setChatBounds: (rect) => ipcRenderer.send('chat:bounds', rect),
  setChatVisible: (visible) => ipcRenderer.send('chat:visible', visible),
  onFill: (cb) => ipcRenderer.on('airlock:fill', (_e, text) => cb(text)),
  openExternal: (url) => ipcRenderer.send('open-external', url),

  initial: ipcRenderer.sendSync('settings:initial'),
  setSettings: (patch) => ipcRenderer.send('settings:set', patch),
  onTheme: (cb) => ipcRenderer.on('theme:changed', (_e, theme) => cb(theme)),
  openDataFolder: () => ipcRenderer.send('data:open'),

  listShells: () => ipcRenderer.invoke('shells:list'),
  ptyStart: (opts) => ipcRenderer.send('pty:start', opts),
  ptyInput: (id, data) => ipcRenderer.send('pty:input', id, data),
  ptyResize: (id, size) => ipcRenderer.send('pty:resize', id, size),
  ptyActivate: (id) => ipcRenderer.send('pty:activate', id),
  ptyClose: (id) => ipcRenderer.send('pty:close', id),
  ptyConfirmClose: (id) => ipcRenderer.invoke('pty:confirm-close', id),
  onPtyData: (cb) => ipcRenderer.on('pty:data', (_e, id, data) => cb(id, data)),
  onPtyExit: (cb) => ipcRenderer.on('pty:exit', (_e, id, code) => cb(id, code)),
  reportCwd: (id, cwd) => ipcRenderer.send('pty:cwd', id, cwd),
  onDownloadDone: (cb) => ipcRenderer.on('download:done', (_e, info) => cb(info)),
  onUsage: (cb) => ipcRenderer.on('usage:update', (_e, usage) => cb(usage)),
  refreshUsage: () => ipcRenderer.send('usage:refresh'),
  listSnippets: () => ipcRenderer.invoke('snippets:list'),
  saveSnippets: (list) => ipcRenderer.invoke('snippets:save', list),
  chooseSnippetsFolder: () => ipcRenderer.invoke('snippets:choose-folder'),
  resetSnippetsFolder: () => ipcRenderer.invoke('snippets:reset-folder'),
  listHistory: () => ipcRenderer.invoke('history:list'),
  addHistory: (command) => ipcRenderer.send('history:add', command),
  saveScratch: (file) => ipcRenderer.invoke('scratch:save', file),
  loadScratchState: () => ipcRenderer.invoke('scratch:load'),
  saveScratchState: (state) => ipcRenderer.send('scratch:state', state),
  loadScrollback: () => ipcRenderer.invoke('scrollback:load'),
  saveScrollback: (tabs) => ipcRenderer.send('scrollback:save', tabs),
  awsProfiles: (id) => ipcRenderer.invoke('aws:profiles', id),
  awsCommand: (id, name) => ipcRenderer.invoke('aws:command', id, name),
});
